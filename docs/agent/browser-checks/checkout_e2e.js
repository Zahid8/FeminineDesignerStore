const { chromium } = require('playwright');
const base = 'http://127.0.0.1:8766';
const results = []; const ok = (n, c, d = '') => { results.push([c, n]); console.log((c ? 'PASS ' : 'FAIL ') + n + (d ? '  — ' + d : '')); };
(async () => {
  const b = await chromium.launch(); const errs = [];
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
  const p = await ctx.newPage(); p.on('pageerror', e => errs.push(e.message));
  await p.goto(base + '/accounts/login/?method=email'); await p.fill('input[name=username]', 'qa@example.com'); await p.fill('input[name=password]', 'Qa-pass-12345!');
  await Promise.all([p.waitForNavigation(), p.click('form.fd-form button[type=submit]')]);
  await p.goto(base + '/products/rani-pink-floral-brocade-blouse/'); await Promise.all([p.waitForNavigation(), p.evaluate(() => document.getElementById('pdp-cart-form').submit())]);
  await p.goto(base + '/products/black-sequin-sweetheart-blouse/'); await Promise.all([p.waitForNavigation(), p.evaluate(() => document.getElementById('pdp-cart-form').submit())]);
  await p.goto(base + '/checkout/', { waitUntil: 'networkidle' }); await p.waitForTimeout(1500);
  ok('saved address preselected', await p.isChecked('input[name=address_id]:not([value=new])'));
  ok('new-address fields hidden', !(await p.isVisible('input[name=address_line1]')));
  ok('delivery dates from saved address PIN', /Delivery by/.test(await p.textContent('[data-eta-line] span')), await p.textContent('[data-eta-line] span'));
  ok('thumbnails in summary', (await p.$$('#checkout-summary .fd-order-thumb img')).length >= 2);
  ok('sticky place-order bar', await p.isVisible('.fd-sticky-pay button'));
  await p.screenshot({ path: 'home/co_top.png' });
  await p.click('.fd-offers li:has-text("FESTIVE10") button'); await p.waitForLoadState('networkidle');
  ok('coupon applied on checkout', (await p.textContent('#checkout-summary')).includes('Coupon (FESTIVE10)'));
  await p.check('text=This is a gift'); await p.fill('#id_gift_message', 'Happy birthday Meera!');
  await p.click('input[value=new]'); await p.waitForTimeout(300); ok('new address reveals fields', await p.isVisible('input[name=address_line1]'));
  await p.click('input[name=address_id]:not([value=new])');
  await p.screenshot({ path: 'home/co_full.png', fullPage: true });
  await Promise.all([p.waitForNavigation(), p.click('.fd-sticky-pay button')]);
  const url = p.url(); ok('order placed', /orders\/.+\/success/.test(url), url.replace(base, ''));
  const body = await p.textContent('body');
  ok('success page shows coupon saving', body.includes('You saved'));
  const w = await p.evaluate(() => document.documentElement.scrollWidth); ok('no sideways scroll', w <= 391, String(w));
  ok('no page errors', errs.length === 0, errs.join(' | '));
  console.log('\nISSUES:', results.filter(r => !r[0]).map(r => r[1]).join('; ') || 'none');
  console.log(url.split('/orders/')[1]);
  await b.close();
})();
